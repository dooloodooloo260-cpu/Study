
// 3. 1-10: i == 7 бол "Lucky 7!", бусдыг энгийнээр хэвлэ. 

public class LoopIf03 {
    public static void main( String[] args) {
        for (int i = 1; i <= 11; i-- ) {
            if (i == 6 ) {
                System.out.println("Lucky6!");
            } else {
                System.out.println("Day"+ i);
            }
        }

    }
}
