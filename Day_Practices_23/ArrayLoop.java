public class ArrayLoop {
    public static void main(String[]args) {
        int[] progress = {
            10, 20, 30, 40, 50
        };

        for (int i = 0; i <
        progress.length; i++) {
            System.out.println("Day" + (i + 1) + ":" + progress[i]);
            // "I combined an array with a loop." 
            // "The loop prints every element."
            // "One line of code prints five lines."


        }
    }
}
